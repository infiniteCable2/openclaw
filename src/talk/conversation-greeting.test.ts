import { beforeEach, describe, expect, it, vi } from "vitest";
import { createAdmittedRunOperatorAuthority } from "../agents/admitted-run-context.js";
import type { RunIsolatedCompletionParams } from "../agents/isolated-completion-types.js";
import type { MsgContext } from "../auto-reply/templating.js";
import { SILENT_REPLY_TOKEN } from "../auto-reply/tokens.js";
import { prepareConversationGreeting } from "./conversation-greeting.js";
import {
  claimConversationInputExecution,
  consumeConversationInputAdmission,
  createConversationInputAdmission,
  prepareConversationReplyContext,
} from "./conversation-input-admission.js";
import type { ConversationInputScopeV1 } from "./conversation-input.types.js";

const mocks = vi.hoisted(() => ({ run: vi.fn(), prepareFacts: vi.fn(), anchors: vi.fn() }));
// mock-isolation: Test the caller's live authority and result ownership, not provider I/O.
vi.mock("../agents/isolated-completion.js", () => ({ runIsolatedCompletion: mocks.run }));
// mock-isolation: No database worker is generated by this source-only authority test.
vi.mock("../gateway/session-sharing-preparation.js", () => ({
  prepareSessionMutationFacts: mocks.prepareFacts,
}));
// mock-isolation: Only the native ordering witness is needed; no transcript payload is read.
vi.mock("../config/sessions/session-transcript-anchor-read.js", () => ({
  readSessionTranscriptAnchorsAsync: mocks.anchors,
}));

async function setup() {
  const scope: ConversationInputScopeV1 = {
    agentId: "example-agent",
    conversationId: "example-call",
    inputId: "example-greeting",
    purpose: "greeting",
  };
  const sessionKey = "agent:example-agent:example-call";
  const context: MsgContext = { AgentId: scope.agentId, SessionKey: sessionKey };
  const state = { current: true };
  const assertCurrent = vi.fn(() => {
    if (!state.current) {
      throw new Error("Original admission revoked");
    }
  });
  const operatorAuthority = createAdmittedRunOperatorAuthority({
    profileId: "assigned-person",
    scopes: [],
    assertCurrent,
  });
  const cap = createConversationInputAdmission({
    scope,
    source: { channelId: "example-channel", sessionKey },
    assertCurrent,
    assertInputCurrent: assertCurrent,
    operatorAuthority,
    prepareContext: () => context,
    requesterProfile: {
      id: "assigned-person",
      displayName: "Alex",
      isCurrent: () => state.current,
    },
  });
  const input = consumeConversationInputAdmission(cap, scope);
  claimConversationInputExecution(input);
  const projected = await prepareConversationReplyContext(input, {
    text: "Greet the caller briefly.",
  });
  mocks.prepareFacts.mockRejectedValue(new Error("Greeting must not await a session"));
  mocks.anchors.mockRejectedValue(new Error("Greeting must not read a transcript"));
  mocks.run.mockResolvedValue({ text: "Good morning!" });
  const onSpeakableText = vi.fn();
  const params = {
    input,
    context: projected,
    cfg: {
      agents: {
        entries: { "example-agent": { identity: { language: "de" } } },
        defaults: {
          model: { primary: "example-provider/example-model@selected-profile" },
          utilityModel: "other-provider/other-model",
        },
      },
    },
    text: "Greet the caller briefly.",
    speech: {
      guidance: "Synthetic general conversation guidance.",
      assertOutputCurrent: vi.fn(),
      onSpeakableText,
      onError: vi.fn(),
      logger: { warn: vi.fn() },
    },
  };
  return {
    params,
    state,
    onSpeakableText,
  };
}

describe("native isolated greeting preparation", () => {
  beforeEach(() => vi.clearAllMocks());

  it("preserves authority and selected account without waiting for a session", async () => {
    const fixture = await setup();
    const result = await prepareConversationGreeting(fixture.params);
    expect(result).toMatchObject({ text: "Good morning!" });
    const run = mocks.run.mock.calls[0]![0] as RunIsolatedCompletionParams;
    expect(run).toMatchObject({
      agentId: "example-agent",
      provider: "example-provider",
      model: "example-model",
      authProfileId: "selected-profile",
      thinkLevel: "off",
      operatorAuthority: fixture.params.input.operatorAuthority,
    });
    expect(run.prompt).toBe(fixture.params.text);
    expect(run.systemPrompt).toContain('Confirmed caller name (data): "Alex".');
    expect(run.systemPrompt).toContain('Default greeting language (data): "de".');
    expect(run.systemPrompt).not.toContain(fixture.params.speech.guidance);
    expect(run.sessionKey).not.toBe(fixture.params.input.source.sessionKey);
    expect(fixture.onSpeakableText).not.toHaveBeenCalled();
    expect(result.delivered).toBeUndefined();
    expect(mocks.prepareFacts).not.toHaveBeenCalled();
    expect(mocks.anchors).not.toHaveBeenCalled();
    expect(result.greeting).toBeUndefined();
    expect(result.greetingPreparation).toMatchObject({
      eventId: "talk-greeting:example-call:example-greeting",
      requesterProfileId: "assigned-person",
    });
  });

  it("keeps original authority live through inference", async () => {
    const fixture = await setup();
    mocks.run.mockImplementation(async (run: RunIsolatedCompletionParams) => {
      fixture.state.current = false;
      expect(() => run.assertCurrent?.()).toThrow();
      return { text: "Not deliverable." };
    });
    await expect(prepareConversationGreeting(fixture.params)).rejects.toThrow();
    expect(fixture.onSpeakableText).not.toHaveBeenCalled();
  });

  it.each(["", SILENT_REPLY_TOKEN])(
    "does not invent readiness from an empty or silent result",
    async (text) => {
      const fixture = await setup();
      mocks.run.mockResolvedValue({ text });
      await expect(prepareConversationGreeting(fixture.params)).rejects.toThrow("no greeting");
      expect(fixture.onSpeakableText).not.toHaveBeenCalled();
    },
  );

  it("retains native failures without speaking or logging provider text", async () => {
    const fixture = await setup();
    const error = new Error("synthetic-provider-detail-not-for-logs");
    mocks.run.mockRejectedValue(error);
    await expect(prepareConversationGreeting(fixture.params)).rejects.toBe(error);
    expect(fixture.params.speech.logger.warn).toHaveBeenCalledOnce();
    expect(JSON.stringify(fixture.params.speech.logger.warn.mock.calls)).not.toContain(
      error.message,
    );
    expect(fixture.onSpeakableText).not.toHaveBeenCalled();
  });

  it("captures native speech metadata without preparing a live output", async () => {
    const fixture = await setup();
    const assertExpressionCurrent = vi.fn();
    const localServiceAdmission = {
      generation: "synthetic-worker",
      signal: new AbortController().signal,
    };
    const expectedSpeechSelection = { provider: "example", model: "prepared", voice: "prepared" };
    mocks.run.mockResolvedValue({
      text: '{"type":"speech","text":"Hello there!","expression":{"parts":[{"text":"Hello there!"}]}}',
    });
    const result = await prepareConversationGreeting({
      ...fixture.params,
      speech: {
        ...fixture.params.speech,
        speechExpressionContext: {
          guidance: "Use native speech presentation.",
          assertCurrent: assertExpressionCurrent,
          localServiceAdmission,
          expectedSpeechSelection,
        },
      },
    });
    expect(result).toMatchObject({
      text: "Hello there!",
      utterances: [{ text: "Hello there!", speech: { tagged: true, text: "Hello there!" } }],
    });
    expect(result.delivered).toBeUndefined();
    expect(result.utterances?.[0]?.localServiceAdmission).toBe(localServiceAdmission);
    expect(result.utterances?.[0]?.expectedSpeechSelection).toBe(expectedSpeechSelection);
    expect(fixture.onSpeakableText).not.toHaveBeenCalled();
    expect(assertExpressionCurrent).toHaveBeenCalled();
  });
});
